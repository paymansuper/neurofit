// ===== i18n: Zweisprachigkeit (Deutsch/Englisch) =====
// Sprache liegt in einem eigenen localStorage-Key, damit sie schon vor dem Profil verfügbar ist.

const LANG_KEY = 'neurofit-lang';

export function getLang() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === 'de' || saved === 'en') return saved;
  return (navigator.language || 'de').toLowerCase().startsWith('de') ? 'de' : 'en';
}

export function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
  location.reload(); // einfachster Weg: komplette UI neu aufbauen
}

/** Wählt aus einem zweisprachigen Objekt {de, en} den Text der aktiven Sprache. */
export function L(obj) {
  if (obj == null || typeof obj !== 'object') return obj;
  return obj[getLang()] ?? obj.de;
}

/** Übersetzt einen Schlüssel, mit {platzhalter}-Ersetzung. */
export function t(key, vars) {
  const lang = getLang();
  let s = STRINGS[lang]?.[key] ?? STRINGS.de[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

